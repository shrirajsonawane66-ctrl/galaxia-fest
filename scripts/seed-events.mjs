/**
 * Seeds the 23 official Galaxia i-Fest 2026 events.
 *
 * With Supabase admin env vars present it upserts into public.events via REST.
 * Without them it seeds the local .data/events.json fallback used by dev, and
 * always regenerates supabase/seeds/20261127_festival_events.sql so the same
 * exact data can be pasted into the Supabase SQL editor.
 *
 * Usage: node scripts/seed-events.mjs
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const seeds = JSON.parse(
  await readFile(path.join(root, "scripts", "events-2026.json"), "utf8")
);

const SAMPLE_IDS = [
  "11111111-1111-4111-8111-111111111111",
  "22222222-2222-4222-8222-222222222222",
  "33333333-3333-4333-8333-333333333333",
  "44444444-4444-4444-8444-444444444444",
  "55555555-5555-4555-8555-555555555555",
  "66666666-6666-4666-8666-666666666666",
];

const slugify = (value) =>
  value.toLowerCase().trim().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 80);

const now = new Date().toISOString();

function seedRows() {
  return seeds.map((seed, index) => {
    const id = `20260000-0000-4000-8000-${String(index + 1).padStart(12, "0")}`;
    const slug = `2026-${slugify(seed.title)}`;
    return {
      id,
      slug,
      day: seed.day,
      sortOrder: seed.sortOrder,
      title: seed.title,
      theme: seed.theme,
      rules: seed.rules,
      whatsappUrl: seed.whatsappUrl ?? null,
      startsAt: null,
      isPublished: false,
      imageUrl: seed.thumbnail,
      imageAlt: `${seed.title} thumbnail`,
      heading: seed.title,
      description: seed.theme || "",
      date: "",
      startTime: "",
      endTime: "",
      eventName: seed.title,
      location: "TBA",
      category: "General",
      actionLabel: "",
      actionType: "none",
      actionUrl: "",
      status: "draft",
      featured: false,
      createdAt: now,
      updatedAt: now,
    };
  });
}

function sqlString(value) {
  return `'${String(value ?? "").replace(/'/g, "''")}'`;
}

function toDbRow(row) {
  return {
    id: row.id,
    slug: row.slug,
    day: row.day,
    theme: row.theme || null,
    starts_at: null,
    rules: row.rules,
    whatsapp_url: row.whatsappUrl,
    is_published: false,
    image_url: row.imageUrl,
    image_alt: row.imageAlt,
    heading: row.heading,
    description: row.description || null,
    date: null,
    start_time: null,
    end_time: null,
    event_name: row.eventName,
    location: row.location,
    category: row.category,
    action_label: null,
    action_type: "none",
    action_url: null,
    status: "draft",
    featured: false,
    sort_order: row.sortOrder,
  };
}

async function writeSql(rows) {
  const lines = [
    "-- Generated by scripts/seed-events.mjs from scripts/events-2026.json.",
    "-- Run AFTER supabase/migrations/20261127_events_system.sql.",
    "-- All 23 rows are drafts: no dates, links or invented details.",
    "",
    "insert into public.events (",
    "  id, slug, day, theme, starts_at, rules, whatsapp_url, is_published,",
    "  image_url, image_alt, heading, description, date, start_time, end_time,",
    "  event_name, location, category, action_label, action_type, action_url,",
    "  status, featured, sort_order",
    ") values",
  ];
  lines.push(
    rows
      .map((row) => {
        const db = toDbRow(row);
        const rules = `array[${row.rules.map(sqlString).join(", ")}]::text[]`;
        return [
          "  (",
          [
            sqlString(db.id),
            sqlString(db.slug),
            String(db.day),
            sqlString(db.theme),
            "null",
            rules,
            db.whatsapp_url ? sqlString(db.whatsapp_url) : "null",
            "false",
            sqlString(db.image_url),
            sqlString(db.image_alt),
            sqlString(db.heading),
            sqlString(db.description),
            "null",
            "null",
            "null",
            sqlString(db.event_name),
            sqlString(db.location),
            sqlString(db.category),
            "null",
            sqlString(db.action_type),
            "null",
            sqlString(db.status),
            "false",
            String(db.sort_order),
          ].join(", "),
          ")",
        ].join("");
      })
      .join(",\n")
  );
  lines.push("on conflict (id) do nothing;", "");
  const target = path.join(root, "supabase", "seeds", "20261127_festival_events.sql");
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, lines.join("\n"), "utf8");
  return target;
}

async function seedLocal(rows) {
  const target = path.join(root, ".data", "events.json");
  let existing = [];
  try {
    existing = JSON.parse(await readFile(target, "utf8"));
    if (!Array.isArray(existing)) existing = [];
  } catch {
    existing = [];
  }
  const seedIds = new Set(rows.map((row) => row.id));
  const byId = new Map(
    existing.filter((event) => seedIds.has(event.id)).map((event) => [event.id, event])
  );
  const kept = existing
    .filter((event) => !seedIds.has(event.id))
    .map((event) =>
      SAMPLE_IDS.includes(event.id)
        ? { ...event, status: "draft", isPublished: false }
        : event
    );
  // Preserve admin edits (dates, links, publish state) on repeated runs.
  const festivalRows = rows.map((row) => byId.get(row.id) ?? row);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, JSON.stringify([...kept, ...festivalRows], null, 2), "utf8");
  return target;
}

async function seedSupabase(rows, url, key) {
  let failures = 0;
  for (let index = 0; index < rows.length; index += 8) {
    const chunk = rows.slice(index, index + 8).map(toDbRow);
    const response = await fetch(`${url}/rest/v1/events?on_conflict=id`, {
      method: "POST",
      headers: {
        apikey: key,
        Authorization: `Bearer ${key}`,
        "Content-Type": "application/json",
        Prefer: "resolution=ignore-duplicates,return=minimal",
      },
      body: JSON.stringify(chunk),
    });
    if (!response.ok) {
      failures += chunk.length;
      console.error(`Supabase chunk failed (${response.status}): ${await response.text()}`);
    }
  }
  return failures;
}

const rows = seedRows();
const day1 = rows.filter((row) => row.day === 1).length;
const day2 = rows.filter((row) => row.day === 2).length;
if (rows.length !== 23 || day1 !== 13 || day2 !== 10) {
  throw new Error(`Seed data mismatch: ${rows.length} rows (${day1} day 1, ${day2} day 2)`);
}

const sqlPath = await writeSql(rows);
const url = process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;

let target;
if (url && key) {
  const failures = await seedSupabase(rows, url, key);
  target = "Supabase public.events";
  if (failures) throw new Error(`${failures} Supabase rows failed to seed`);
} else {
  target = await seedLocal(rows);
}

console.log(
  `Seeded ${rows.length} events (${day1} day 1, ${day2} day 2) into ${target}.`
);
console.log(`SQL seed file: ${sqlPath}`);
console.log("All rows: isPublished=false, startsAt=null; WhatsApp links included where provided.");
