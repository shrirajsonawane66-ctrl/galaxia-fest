/**
 * Imports the 21 published Events-tab records from the reference Galaxia
 * project into this site without touching any existing admin records.
 *
 * With Supabase admin env vars present it upserts into public.events via REST.
 * Without them it merges into the local .data/events.json fallback. It also
 * regenerates supabase/seeds/20261127_reference_events.sql.
 *
 * Usage: npm run seed:reference-events
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const reference = JSON.parse(
  await readFile(path.join(root, "scripts", "reference-events-2026.json"), "utf8")
);
const festival = JSON.parse(
  await readFile(path.join(root, "scripts", "events-2026.json"), "utf8")
);

const SAMPLE_IDS = [
  "11111111-1111-4111-8111-111111111111",
  "22222222-2222-4222-8222-222222222222",
  "33333333-3333-4333-8333-333333333333",
  "44444444-4444-4444-8444-444444444444",
  "55555555-5555-4555-8555-555555555555",
  "66666666-6666-4666-8666-666666666666",
];

const slugify = (value) =>
  value.toLowerCase().trim().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 80);

const now = new Date().toISOString();

/** The 23 official programme drafts, kept as-is for the admin screen. */
function festivalRows() {
  return festival.map((seed, index) => ({
    id: `20260000-0000-4000-8000-${String(index + 1).padStart(12, "0")}`,
    slug: `2026-${slugify(seed.title)}`,
    day: seed.day,
    sortOrder: seed.sortOrder,
    title: seed.title,
    theme: seed.theme,
    rules: seed.rules,
    startsAt: null,
    whatsappUrl: seed.whatsappUrl ?? null,
    isPublished: false,
    imageUrl: seed.thumbnail,
    imageAlt: `${seed.title} thumbnail`,
    heading: seed.title,
    description: seed.theme || "",
    date: "",
    startTime: "",
    endTime: "",
    eventName: seed.title,
    location: "TBA",
    category: "General",
    actionLabel: "",
    actionType: "none",
    actionUrl: "",
    status: "draft",
    featured: false,
    createdAt: now,
    updatedAt: now,
  }));
}

/** The 21 published cards from the reference Events tab, field-for-field. */
function referenceRows() {
  return reference.map((event) => ({
    id: event.id,
    slug: event.slug,
    day: event.heading === "Day 1" ? 1 : 2,
    sortOrder: event.sortOrder,
    title: event.eventName,
    theme: "",
    rules: event.rules ?? [],
    startsAt: null,
    whatsappUrl: event.whatsappUrl ?? null,
    isPublished: true,
    imageUrl: event.imageUrl,
    imageAlt: event.imageAlt,
    heading: event.heading,
    description: event.description,
    date: event.date,
    startTime: event.startTime,
    endTime: "",
    eventName: event.eventName,
    location: event.location,
    category: event.category,
    actionLabel: "",
    actionType: event.actionType,
    actionUrl: "",
    status: event.status,
    featured: event.featured,
    createdAt: event.createdAt,
    updatedAt: event.updatedAt,
    dateTbd: event.dateTbd,
  }));
}

function toDbRow(row) {
  return {
    id: row.id,
    slug: row.slug,
    day: row.day,
    theme: row.theme || null,
    starts_at: null,
    rules: row.rules,
    whatsapp_url: row.whatsappUrl,
    is_published: row.isPublished,
    image_url: row.imageUrl || null,
    image_alt: row.imageAlt || null,
    heading: row.heading,
    description: row.description || null,
    date: row.date || null,
    start_time: row.startTime || null,
    end_time: null,
    event_name: row.eventName,
    location: row.location,
    category: row.category,
    action_label: null,
    action_type: row.actionType || "none",
    action_url: null,
    status: row.status,
    featured: row.featured,
    sort_order: row.sortOrder,
    created_at: row.createdAt,
    updated_at: row.updatedAt,
  };
}

function sqlString(value) {
  return `'${String(value ?? "").replace(/'/g, "''")}'`;
}

function sqlStringArray(values) {
  return `array[${values.map(sqlString).join(", ")}]::text[]`;
}

async function writeSql(rows) {
  const lines = [
    "-- Generated by scripts/seed-reference-events.mjs from scripts/reference-events-2026.json.",
    "-- Run AFTER supabase/migrations/20261127_events_system.sql.",
    "-- The 21 published rows are the exact records from the reference Events tab.",
    "",
    "insert into public.events (",
    "  id, slug, day, theme, starts_at, rules, whatsapp_url, is_published,",
    "  image_url, image_alt, heading, description, date, start_time, end_time,",
    "  event_name, location, category, action_label, action_type, action_url,",
    "  status, featured, sort_order, created_at, updated_at",
    ") values",
  ];
  lines.push(
    rows
      .map((row) => {
        const db = toDbRow(row);
        return [
          "  (",
          [
            sqlString(db.id),
            sqlString(db.slug),
            String(db.day),
            sqlString(db.theme),
            "null",
            sqlStringArray(db.rules),
            db.whatsapp_url ? sqlString(db.whatsapp_url) : "null",
            "true",
            sqlString(db.image_url),
            sqlString(db.image_alt),
            sqlString(db.heading),
            sqlString(db.description),
            sqlString(db.date),
            sqlString(db.start_time),
            "null",
            sqlString(db.event_name),
            sqlString(db.location),
            sqlString(db.category),
            "null",
            sqlString(db.action_type),
            "null",
            sqlString(db.status),
            "false",
            String(db.sort_order),
            sqlString(db.created_at),
            sqlString(db.updated_at),
          ].join(", "),
          ")",
        ].join("");
      })
      .join(",\n")
  );
  lines.push("on conflict (id) do nothing;", "");
  const target = path.join(root, "supabase", "seeds", "20261127_reference_events.sql");
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, lines.join("\n"), "utf8");
  return target;
}

async function seedLocal(rows) {
  const target = path.join(root, ".data", "events.json");
  let existing = [];
  try {
    existing = JSON.parse(await readFile(target, "utf8"));
    if (!Array.isArray(existing)) existing = [];
  } catch {
    existing = [];
  }

  const seedIds = new Set(rows.map((row) => row.id));
  const byId = new Map(
    existing.filter((event) => seedIds.has(event.id)).map((event) => [event.id, event])
  );
  const kept = existing
    .filter((event) => !seedIds.has(event.id))
    .map((event) =>
      SAMPLE_IDS.includes(event.id)
        ? { ...event, status: "draft", isPublished: false }
        : event
    );
  // Repeated runs never overwrite admin edits.
  const seeded = rows.map((row) => byId.get(row.id) ?? row);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, JSON.stringify([...kept, ...seeded], null, 2), "utf8");
  return target;
}

async function seedSupabase(rows, url, key) {
  let failures = 0;
  for (let index = 0; index < rows.length; index += 8) {
    const chunk = rows.slice(index, index + 8).map(toDbRow);
    const response = await fetch(`${url}/rest/v1/events?on_conflict=id`, {
      method: "POST",
      headers: {
        apikey: key,
        Authorization: `Bearer ${key}`,
        "Content-Type": "application/json",
        Prefer: "resolution=ignore-duplicates,return=minimal",
      },
      body: JSON.stringify(chunk),
    });
    if (!response.ok) {
      failures += chunk.length;
      console.error(`Supabase chunk failed (${response.status}): ${await response.text()}`);
    }
  }
  return failures;
}

const publishedRows = referenceRows();
const day1 = publishedRows.filter((row) => row.day === 1).length;
const day2 = publishedRows.filter((row) => row.day === 2).length;
if (publishedRows.length !== 21 || day1 !== 11 || day2 !== 10) {
  throw new Error(
    `Reference data mismatch: ${publishedRows.length} rows (${day1} day 1, ${day2} day 2)`
  );
}

const sqlPath = await writeSql(publishedRows);
const url = process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;

let target;
if (url && key) {
  const failures = await seedSupabase(publishedRows, url, key);
  target = "Supabase public.events";
  if (failures) throw new Error(`${failures} Supabase rows failed to seed`);
} else {
  target = await seedLocal([...festivalRows(), ...publishedRows]);
}

console.log(
  `Seeded ${publishedRows.length} published reference events (${day1} day 1, ${day2} day 2) into ${target}.`
);
console.log(`SQL seed file: ${sqlPath}`);
console.log("Reference rows: exact titles, descriptions, dates, categories, thumbnails, rules and WhatsApp links.");
